// src/app/api/wish/route.ts
// POST /api/wish — create a new personalized wish
import { NextRequest, NextResponse } from 'next/server';
import { createServiceClient } from '@/lib/supabase/server';
import { checkRateLimit, getAnonymousId } from '@/lib/rate-limit';
import type { CreateWishInput, RecipientType } from '@/types';

const MAX_NAME_LENGTH = 50;
const MAX_MSG_LENGTH = 280;

const ALLOWED_RECIPIENT_TYPES: RecipientType[] = [
  'friend', 'family', 'student', 'teacher', 'colleague', 'everyone',
];

function sanitizeText(input: unknown, max: number): string {
  if (typeof input !== 'string') return '';
  return input
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#x27;')
    .trim()
    .slice(0, max);
}


export async function GET(request: NextRequest): Promise<NextResponse> {
  try {
    const { searchParams } = new URL(request.url);
    const token = searchParams.get('token');

    if (!token || typeof token !== 'string') {
      return NextResponse.json({ error: 'Token is required' }, { status: 400 });
    }

    const supabase = createServiceClient();
    const { data: wish, error } = await supabase
      .from('wishes')
      .select('id, public_token, display_name, recipient_type, personal_message, template_version, parent_token, created_at, expires_at')
      .eq('public_token', token)
      .single();

    if (error || !wish) {
      return NextResponse.json({ error: 'Wish not found' }, { status: 404 });
    }

    // Check if expired
    if (wish.expires_at && new Date(wish.expires_at) < new Date()) {
      return NextResponse.json({ error: 'This Christmas greeting has expired.' }, { status: 410 });
    }

    return NextResponse.json({ wish }, { status: 200 });
  } catch (err) {
    console.error('Error fetching wish:', err);
    return NextResponse.json({ error: 'Failed to fetch wish' }, { status: 500 });
  }
}

export async function POST(request: NextRequest): Promise<NextResponse> {
  try {
    // Rate limiting
    const anonymousId = await getAnonymousId(request);
    const rateLimitResult = checkRateLimit(`wish:${anonymousId}`);
    if (!rateLimitResult.allowed) {
      return NextResponse.json(
        { success: false, error: 'Too many requests. Please try again shortly.' },
        {
          status: 429,
          headers: {
            'Retry-After': String(rateLimitResult.retryAfter ?? 60),
          },
        }
      );
    }

    let body: CreateWishInput;
    try {
      body = await request.json();
    } catch {
      return NextResponse.json(
        { success: false, error: 'Invalid request body.' },
        { status: 400 }
      );
    }

    // Validate display name (required)
    const displayName = sanitizeText(body.display_name, MAX_NAME_LENGTH);
    if (!displayName || displayName.length < 2) {
      return NextResponse.json(
        { success: false, error: 'Display name must be at least 2 characters.' },
        { status: 400 }
      );
    }

    // Validate recipient type (optional)
    const recipientType: RecipientType =
      ALLOWED_RECIPIENT_TYPES.includes(body.recipient_type as RecipientType)
        ? (body.recipient_type as RecipientType)
        : 'everyone';

    // Validate personal message (optional)
    const personalMessage = body.personal_message
      ? sanitizeText(body.personal_message, MAX_MSG_LENGTH)
      : null;

    // Validate parent_token (optional — for viral chain tracking)
    const parentToken =
      typeof body.parent_token === 'string' && /^[A-Za-z0-9_-]{10,40}$/.test(body.parent_token)
        ? body.parent_token
        : null;

    // Check campaign is active
    const supabase = createServiceClient();
    const { data: config, error: configError } = await supabase
      .from('campaign_config')
      .select('campaign_status, end_at')
      .eq('id', '00000000-0000-0000-0000-000000000001')
      .single();

    if (configError) {
      console.error('Campaign config error:', configError);
      // If Supabase isn't configured, proceed anyway (dev mode)
    }

    if (config && config.campaign_status !== 'active') {
      return NextResponse.json(
        { success: false, error: 'The Christmas wish campaign is not currently active.' },
        { status: 403 }
      );
    }

    if (config?.end_at && new Date(config.end_at) < new Date()) {
      return NextResponse.json(
        { success: false, error: 'The Christmas wish campaign has ended.' },
        { status: 403 }
      );
    }

    // Insert the wish — public_token is auto-generated by DB
    const { data: wish, error: wishError } = await supabase
      .from('wishes')
      .insert({
        display_name: displayName,
        recipient_type: recipientType,
        personal_message: personalMessage,
        template_version: 'v1',
        parent_token: parentToken,
      })
      .select('public_token')
      .single();

    if (wishError || !wish) {
      console.error('Wish creation error:', wishError);
      return NextResponse.json(
        { success: false, error: 'Failed to create your Christmas wish. Please try again.' },
        { status: 500 }
      );
    }

    // Record analytics event (wish_created) — best-effort
    try {
      await supabase.from('analytics_events').insert({
        event_type: 'wish_created',
        wish_id: wish.public_token,
        campaign_source: parentToken ? 'shared_link' : 'direct',
      });
    } catch { /* ignore */ }

    return NextResponse.json(
      { success: true, public_token: wish.public_token },
      { status: 201 }
    );
  } catch (err) {
    console.error('Unexpected error in POST /api/wish:', err);
    return NextResponse.json(
      { success: false, error: 'An unexpected error occurred.' },
      { status: 500 }
    );
  }
}
